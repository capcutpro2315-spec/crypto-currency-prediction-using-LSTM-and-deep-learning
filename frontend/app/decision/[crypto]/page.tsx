"use client";

import { useState, useEffect } from "react";
import { useParams } from "next/navigation";
import Link from "next/link";
import { ShieldCheck, ChevronLeft, RefreshCw, TrendingUp, AlertTriangle } from "lucide-react";
import { getDecisionSupport, CryptoDecisionResponse } from "@/lib/api";
import { DecisionSignal } from "@/components/decision/DecisionSignal";
import { DecisionReasons } from "@/components/decision/DecisionReasons";
import { LoadingState } from "@/components/common/LoadingState";
import { ErrorState } from "@/components/common/ErrorState";
import { Button } from "@/components/common/Button";
import { useCrypto } from "@/lib/CryptoContext";

export default function DecisionCryptoPage() {
  const params = useParams();
  const rawCrypto = (params?.crypto as string) || "BTC-USD";
  const ticker = rawCrypto.includes("-") ? rawCrypto.toUpperCase() : `${rawCrypto.toUpperCase()}-USD`;
  const { setSelectedTicker } = useCrypto();

  const [decisionData, setDecisionData] = useState<CryptoDecisionResponse | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    if (ticker) {
      setSelectedTicker(ticker);
    }
  }, [ticker, setSelectedTicker]);

  const fetchDecision = async () => {
    setLoading(true);
    setError(null);
    try {
      const res = await getDecisionSupport(ticker);
      setDecisionData(res);
    } catch (err: any) {
      setError(err.message || "Failed to load decision-support signals.");
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchDecision();
  }, [ticker]);

  return (
    <div className="space-y-8">
      {/* Top Header */}
      <div className="flex flex-col md:flex-row md:items-center justify-between gap-4 pb-6 border-b border-slate-800">
        <div>
          <Link href="/markets" className="inline-flex items-center space-x-1 text-xs text-slate-400 hover:text-blue-400 mb-2 transition-colors">
            <ChevronLeft className="w-4 h-4" />
            <span>Back to Markets Explorer</span>
          </Link>
          <div className="flex items-center space-x-2">
            <h1 className="text-3xl font-extrabold text-white">AI Decision Support Engine</h1>
            <span className="px-2.5 py-0.5 rounded-lg bg-emerald-500/10 border border-emerald-500/30 text-xs font-mono text-emerald-400">
              {ticker}
            </span>
          </div>
          <p className="text-sm text-slate-400 mt-1">
            Algorithmic decision signals, confidence metrics, and risk factors synthesis.
          </p>
        </div>

        <div className="flex items-center space-x-3 self-start md:self-auto">
          <Button
            href={`/prediction/${encodeURIComponent(ticker)}`}
            variant="primary"
            size="md"
            icon={<TrendingUp className="w-4 h-4" />}
          >
            Run Forecast
          </Button>

          <button
            onClick={fetchDecision}
            disabled={loading}
            className="inline-flex items-center space-x-2 px-4 py-2 bg-slate-800 hover:bg-slate-700 text-slate-300 text-sm font-medium rounded-xl border border-slate-700 transition-colors cursor-pointer"
          >
            <RefreshCw className={`w-4 h-4 ${loading ? "animate-spin" : ""}`} />
            <span>Refresh Signal</span>
          </button>
        </div>
      </div>

      {/* Main Content State Handler */}
      {loading ? (
        <LoadingState message={`Analyzing decision-support signals for ${ticker}...`} />
      ) : error ? (
        <ErrorState title="Signal Unavailable" message={error} onRetry={fetchDecision} />
      ) : decisionData ? (
        <div className="space-y-8">
          {/* Main Decision Signal Card */}
          <DecisionSignal
            decision={decisionData.decision}
            decisionScore={decisionData.decision_score}
            confidenceScore={decisionData.confidence_score}
            riskLabel={decisionData.risk_label}
            expectedChange={decisionData.expected_change_percent}
          />

          {/* Supporting & Risk Reasons Breakdown */}
          <DecisionReasons
            supportingFactors={decisionData.supporting_factors}
            riskFactors={decisionData.risk_factors}
          />

          {/* Educational Disclaimer Banner */}
          <div className="p-4 bg-slate-900/40 border border-slate-800 rounded-xl text-xs text-slate-400 flex items-center space-x-3">
            <AlertTriangle className="w-5 h-5 text-amber-400 shrink-0" />
            <p>
              <strong>AI Decision-Support Disclaimer:</strong> This decision signal is generated by an algorithmic rule engine combining deep learning forecasts, test set confidence scores, and historical market volatility. Cryptocurrency markets are highly volatile and forecasts do NOT guarantee future returns or constitute financial advice.
            </p>
          </div>
        </div>
      ) : null}
    </div>
  );
}
