"use client";

import React from "react";
import { Layers, ShieldCheck, TrendingUp, TrendingDown, Info } from "lucide-react";
import { Card } from "@/components/common/Card";
import { CryptoPredictionResponse } from "@/lib/api";

interface PredictionScenariosProps {
  ticker: string;
  prediction: CryptoPredictionResponse | null;
}

function formatPrice(val: number | undefined | null): string {
  if (val === undefined || val === null || isNaN(val) || val <= 0) return "Unavailable";
  return new Intl.NumberFormat("en-US", {
    style: "currency",
    currency: "USD",
    minimumFractionDigits: val < 1 ? 4 : 2,
    maximumFractionDigits: val < 1 ? 6 : 2,
  }).format(val);
}

export function PredictionScenarios({ ticker, prediction }: PredictionScenariosProps) {
  const isAvailable = prediction?.prediction_available !== false && !!prediction?.predicted_price;
  const expectedPrice = prediction?.predicted_price;
  const expectedChange = prediction?.expected_change_percent;

  const scenarios = (prediction as any)?.scenarios;
  const scenariosAvailable = scenarios?.available === true;
  const bestPrice = scenarios?.best_case;
  const worstPrice = scenarios?.worst_case;

  const isPos = expectedChange !== undefined && expectedChange !== null ? expectedChange >= 0 : null;

  return (
    <section className="space-y-4">
      <div>
        <h2 className="text-xl sm:text-2xl font-bold text-white flex items-center space-x-2">
          <Layers className="w-5 h-5 text-indigo-400" />
          <span>POSSIBLE FUTURE SCENARIOS</span>
        </h2>
        <p className="text-xs text-slate-400">
          Estimated price range projections based on statistical model error boundaries for {ticker}
        </p>
      </div>

      <div className="grid grid-cols-1 md:grid-cols-3 gap-6">
        {/* CARD 1: BEST CASE */}
        <Card variant="hover" className="space-y-3 relative overflow-hidden border-emerald-500/30">
          <div className="flex items-center justify-between">
            <span className="text-xs font-extrabold text-emerald-400 uppercase tracking-wider flex items-center space-x-1">
              <TrendingUp className="w-4 h-4" />
              <span>BEST CASE</span>
            </span>
            <span className="text-[10px] font-mono text-emerald-400 bg-emerald-500/10 px-2 py-0.5 rounded border border-emerald-500/20">
              Upside Scenario
            </span>
          </div>

          <div className="py-2">
            {scenariosAvailable && bestPrice != null ? (
              <div className="space-y-1">
                <div className="text-2xl font-extrabold text-emerald-400 font-mono">
                  {formatPrice(bestPrice)}
                </div>
                <p className="text-xs text-slate-300">Favorable upside boundary (+1.25 RMSE)</p>
              </div>
            ) : (
              <div>
                <div className="text-base font-bold text-slate-400">
                  Scenario analysis unavailable
                </div>
                <p className="text-xs text-slate-500 mt-1 leading-relaxed">
                  Requires historical test evaluation error bounds.
                </p>
              </div>
            )}
          </div>

          <div className="text-[11px] text-slate-500 pt-2 border-t border-slate-800">
            * Upper prediction uncertainty bound.
          </div>
        </Card>

        {/* CARD 2: EXPECTED CASE */}
        <Card variant="gradient" className="space-y-3 relative overflow-hidden border-blue-500/40 shadow-xl">
          <div className="flex items-center justify-between">
            <span className="text-xs font-extrabold text-blue-400 uppercase tracking-wider flex items-center space-x-1">
              <ShieldCheck className="w-4 h-4" />
              <span>EXPECTED CASE</span>
            </span>
            <span className="text-[10px] font-mono text-blue-400 bg-blue-500/10 px-2 py-0.5 rounded border border-blue-500/20">
              Central Forecast
            </span>
          </div>

          {isAvailable ? (
            <div className="py-1 space-y-1">
              <div className="text-2xl font-extrabold text-white font-mono">
                {formatPrice(expectedPrice)}
              </div>
              <div
                className={`text-xs font-bold font-mono ${
                  isPos ? "text-emerald-400" : "text-rose-400"
                }`}
              >
                Expected Movement: {isPos ? "+" : ""}
                {expectedChange?.toFixed(2)}%
              </div>
            </div>
          ) : (
            <div className="text-sm font-bold text-slate-400 py-2">
              Model forecast unavailable
            </div>
          )}

          <p className="text-xs text-slate-300 leading-relaxed">
            The central forecast generated by the AI model.
          </p>

          <div className="text-[11px] text-slate-500 pt-2 border-t border-slate-800">
            Baseline expected outcome.
          </div>
        </Card>

        {/* CARD 3: WORST CASE */}
        <Card variant="hover" className="space-y-3 relative overflow-hidden border-rose-500/30">
          <div className="flex items-center justify-between">
            <span className="text-xs font-extrabold text-rose-400 uppercase tracking-wider flex items-center space-x-1">
              <TrendingDown className="w-4 h-4" />
              <span>WORST CASE</span>
            </span>
            <span className="text-[10px] font-mono text-rose-400 bg-rose-500/10 px-2 py-0.5 rounded border border-rose-500/20">
              Downside Scenario
            </span>
          </div>

          <div className="py-2">
            {scenariosAvailable && worstPrice != null ? (
              <div className="space-y-1">
                <div className="text-2xl font-extrabold text-rose-400 font-mono">
                  {formatPrice(worstPrice)}
                </div>
                <p className="text-xs text-slate-300">Downside risk boundary (-1.25 RMSE)</p>
              </div>
            ) : (
              <div>
                <div className="text-base font-bold text-slate-400">
                  Scenario analysis unavailable
                </div>
                <p className="text-xs text-slate-500 mt-1 leading-relaxed">
                  Requires historical test evaluation error bounds.
                </p>
              </div>
            )}
          </div>

          <div className="text-[11px] text-slate-500 pt-2 border-t border-slate-800">
            * Lower prediction uncertainty bound.
          </div>
        </Card>
      </div>
    </section>
  );
}
