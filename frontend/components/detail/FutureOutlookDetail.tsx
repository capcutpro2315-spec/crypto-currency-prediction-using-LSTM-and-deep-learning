"use client";

import React from "react";
import { Sparkles, ArrowRight, TrendingUp, TrendingDown, AlertCircle } from "lucide-react";
import { Card } from "@/components/common/Card";
import { CryptoPredictionResponse, ModelStatusResponse } from "@/lib/api";

interface FutureOutlookDetailProps {
  ticker: string;
  cryptoName: string;
  prediction: CryptoPredictionResponse | null;
  modelStatus: ModelStatusResponse | null;
  loading: boolean;
}

function formatPrice(val: number | undefined | null): string {
  if (val === undefined || val === null || isNaN(val)) return "Unavailable";
  return new Intl.NumberFormat("en-US", {
    style: "currency",
    currency: "USD",
    minimumFractionDigits: val < 1 ? 4 : 2,
    maximumFractionDigits: val < 1 ? 6 : 2,
  }).format(val);
}

export function FutureOutlookDetail({
  ticker,
  cryptoName,
  prediction,
  modelStatus,
  loading,
}: FutureOutlookDetailProps) {
  const isAvailable = prediction?.prediction_available !== false && !!prediction?.predicted_price;
  const currentPrice = prediction?.current_price;
  const predictedPrice = prediction?.predicted_price;
  const changePercent = prediction?.expected_change_percent;

  const isPos = changePercent != null ? changePercent >= 0 : null;

  let explanationText = "Current analysis points toward sideways price movement.";
  if (changePercent != null) {
    if (changePercent > 0.5) {
      explanationText = "Current analysis points toward a possible upward movement.";
    } else if (changePercent < -0.5) {
      explanationText = "Current analysis points toward a possible downward movement.";
    }
  }

  return (
    <Card variant="gradient" className="space-y-6 border-blue-500/30 shadow-2xl">
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-2">
        <div>
          <h2 className="text-xl sm:text-2xl font-extrabold text-white flex items-center space-x-2">
            <Sparkles className="w-5 h-5 text-emerald-400" />
            <span>Where Could It Go?</span>
          </h2>
          <p className="text-xs text-slate-300 mt-1">
            Near-future price expectation generated by our algorithmic analysis
          </p>
        </div>

        <div className="flex items-center space-x-1.5 text-xs text-emerald-400 bg-emerald-500/10 px-3 py-1.5 rounded-xl border border-emerald-500/30 w-fit font-semibold">
          <span>AI Forecast Engine</span>
        </div>
      </div>

      {loading ? (
        <div className="p-8 space-y-4 bg-slate-950/60 rounded-2xl border border-slate-800 animate-pulse">
          <div className="h-6 w-48 bg-slate-800 rounded-md" />
          <div className="h-10 w-full bg-slate-800 rounded-xl" />
        </div>
      ) : !isAvailable ? (
        <div className="p-6 bg-slate-950/60 rounded-2xl border border-slate-800 space-y-3">
          <div className="flex items-start space-x-3 text-amber-400">
            <AlertCircle className="w-5 h-5 shrink-0 mt-0.5" />
            <div>
              <h3 className="text-sm font-bold text-slate-200">
                Future outlook is currently unavailable for {cryptoName}.
              </h3>
              <p className="text-xs text-slate-400 mt-1">
                {modelStatus?.message || `Sufficient price history or active model configuration is required.`}
              </p>
            </div>
          </div>
        </div>
      ) : (
        <div className="p-6 bg-slate-950/80 rounded-2xl border border-slate-800/90 shadow-2xl space-y-6">
          <div className="grid grid-cols-1 md:grid-cols-3 gap-6 items-center">
            {/* CURRENT PRICE */}
            <div className="space-y-1">
              <span className="text-xs font-semibold text-slate-400 uppercase tracking-wider block">
                CURRENT PRICE
              </span>
              <div className="text-2xl sm:text-3xl font-extrabold text-white font-mono">
                {formatPrice(currentPrice)}
              </div>
              <span className="text-[11px] text-slate-500">Latest market closing rate</span>
            </div>

            {/* TRANSITION & HORIZON */}
            <div className="flex flex-col items-center justify-center space-y-2 py-2">
              <div className="flex items-center space-x-2 text-blue-400">
                <span className="text-xs font-mono font-bold uppercase tracking-wider text-slate-400">
                  AI Forecast
                </span>
                <ArrowRight className="w-5 h-5 text-blue-400 animate-pulse" />
              </div>
              <span className="text-[11px] font-medium text-slate-400 bg-slate-900 px-2.5 py-1 rounded-full border border-slate-800 font-mono">
                Horizon: Next Day (1D)
              </span>
            </div>

            {/* EXPECTED PRICE */}
            <div className="space-y-1 md:text-right">
              <span className="text-xs font-semibold text-emerald-400 uppercase tracking-wider block">
                EXPECTED PRICE
              </span>
              <div className="text-2xl sm:text-3xl font-extrabold text-emerald-400 font-mono">
                {formatPrice(predictedPrice)}
              </div>
              <div
                className={`inline-flex items-center space-x-1 text-xs font-bold font-mono px-2 py-0.5 rounded-md ${
                  isPos
                    ? "bg-emerald-500/10 text-emerald-400 border border-emerald-500/30"
                    : "bg-rose-500/10 text-rose-400 border border-rose-500/30"
                }`}
              >
                {isPos ? <TrendingUp className="w-3.5 h-3.5" /> : <TrendingDown className="w-3.5 h-3.5" />}
                <span>
                  Expected Movement: {isPos ? "+" : ""}
                  {changePercent?.toFixed(2)}%
                </span>
              </div>
            </div>
          </div>

          {/* Plain Language Banner */}
          <div className="p-4 bg-slate-900/90 rounded-xl border border-slate-800 text-sm text-slate-200 flex items-center space-x-3">
            <Sparkles className="w-4 h-4 text-blue-400 shrink-0" />
            <span>&quot;{explanationText}&quot;</span>
          </div>
        </div>
      )}
    </Card>
  );
}
